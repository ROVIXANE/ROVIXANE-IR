#!/usr/bin/env python3
"""Generate WebAssets.h from data/ for Arduino IDE / ArduinoDroid builds.

No Node/npm and no LittleFS upload plugin are needed: the dashboard and
starter database are compiled into firmware flash as PROGMEM arrays.

Every byte is emitted as ``static_cast<char>(0xNN)``. This is deliberate:
UTF-8 Bengali text and emoji contain bytes above 0x7F, and a plain
``0xE0`` initializer would be a narrowing conversion from int to char on
strict C++ compilers such as GCC.

Usage:
  python3 tools/generate_assets.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "WebAssets.h"

FILES = [
    ("kWebIndexHtml", "index.html", "Dashboard HTML"),
    ("kWebAppCss", "app.css", "Dashboard CSS"),
    ("kWebAppJs", "app.js", "Dashboard JavaScript"),
    ("kStarterDevicesJson", "devices.json", "Starter signal database"),
]


def emit_array(name, payload, comment):
    lines = [f"// {comment} ({len(payload)} bytes)",
             f"const char {name}[] PROGMEM = {{"]
    for i in range(0, len(payload), 20):
        chunk = payload[i:i + 20]
        lines.append("  " +
                     ",".join(f"static_cast<char>(0x{b:02X})" for b in chunk) +
                     ",")
    lines.append("  static_cast<char>(0x00)")
    lines.append("};")
    lines.append(f"const size_t {name}Len = sizeof({name}) - 1;")
    lines.append("")
    return lines


def build_header():
    """Return the exact generated header text (also used by the asset tests)."""
    out = [
        "// AUTO-GENERATED by tools/generate_assets.py - do not edit by hand.",
        "#ifndef IHR_WEB_ASSETS_H",
        "#define IHR_WEB_ASSETS_H",
        "",
        "#include <Arduino.h>",
        "",
    ]
    for name, filename, comment in FILES:
        path = DATA / filename
        if not path.exists():
            raise SystemExit(f"Missing {path}")
        out.extend(emit_array(name, path.read_bytes(), comment))
    out.extend(["#endif", ""])
    return "\n".join(out)


def main():
    OUT.write_text(build_header(), encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
